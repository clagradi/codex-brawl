const FONT_CACHE = {};
// Draw text with its baseline-top at (x,y). size = pixel scale. align: left|center|right.
// Returns the drawn width. Uses a per-string cache canvas so HUD text costs one drawImage.
function ptext(ctx, str, x, y, size = 2, col = '#fff', align = 'left', shadow = true) {
  str = String(str).toUpperCase();
  const key = str + '|' + col + '|' + (shadow ? 1 : 0);
  let cv = FONT_CACHE[key];
  if (!cv) {
    const w = str.length * 6 + 1, h = 8 + 1;
    cv = document.createElement('canvas'); cv.width = w; cv.height = h; const c = cv.getContext('2d');
    const draw = (dx, dy, color) => { c.fillStyle = color; [...str].forEach((ch, i) => { const g = GLYPHS[ch] || GLYPHS['?']; g.forEach((row, ry) => { for (let rx = 0; rx < 5; rx++) if (row[rx] === '#') c.fillRect(i * 6 + rx + dx, ry + dy, 1, 1); }); }); };
    if (shadow) draw(1, 1, '#000');
    draw(0, 0, col);
    FONT_CACHE[key] = cv;
    if (Object.keys(FONT_CACHE).length > 600) for (const k in FONT_CACHE) { delete FONT_CACHE[k]; break; }
  }
  const w = (str.length * 6 - 1) * size;
  const ox = align === 'center' ? -w / 2 : align === 'right' ? -w : 0;
  ctx.save(); ctx.imageSmoothingEnabled = false; ctx.drawImage(cv, Math.round(x + ox), Math.round(y), cv.width * size, cv.height * size); ctx.restore();
  return w;
}
function ptextWidth(str, size = 2) { return (String(str).length * 6 - 1) * size; }
